// The app standard's rule numbers, for the test of an app's record (docs/app-standard.md 'The app's
// record'): every numbered section's number and title, and the id of every rule in it, read from
// the page's '## <n>. <title>' headings and its bold rule lines ('**13.2a Every body …'), written
// to src/release/__tests__/support/standard-rules.json.
//
//   node scripts/generate-standard-rules.mjs
//
// Run it after a change to docs/app-standard.md that adds, removes or renumbers a section or a
// rule, and commit the JSON with the page. src/release/__tests__/app-record.test.ts runs the same
// function in the template and fails while the committed file differs from what this script would
// write. A copy of the template has no docs/app-standard.md: it keeps the JSON it was copied with,
// and its TEMPLATE.md names the commit of the standard it was read at.
//
// What it refuses, naming the line: a rule outside a numbered section or under another section's
// number, a section or a rule listed twice, and a numbered section with no title. Lines inside a
// fenced block (the page's example record) are never read as headings or rules.

import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** The page read, and the list written, from the repository root. */
export const SOURCE_PATH = 'docs/app-standard.md';
export const OUTPUT_PATH = 'src/release/__tests__/support/standard-rules.json';
/** The one line at the top of the file, for a person who opens it. */
export const GENERATED_NOTE =
  'Generated by scripts/generate-standard-rules.mjs from docs/app-standard.md. Do not edit by hand: run node scripts/generate-standard-rules.mjs.';

const SECTION = /^## (\d+)\.\s+(.*)$/;
const ANY_SECTION = /^## /;
const RULE = /^\*\*(\d+)\.(\d+[a-z]?) /;
const FENCE = /^```/;
const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** The page does not read as the standard: a rule out of place, or a number used twice. */
export class StandardError extends Error {}

function fail(line, message) {
  throw new StandardError(`${SOURCE_PATH} line ${line}: ${message}`);
}

/** A numbered section, opened by its heading, with no rules yet. */
function openSection(state, match, line) {
  const [, id, title] = match;
  if (title.trim() === '') fail(line, `section ${id} has no title`);
  if (state.sections.some((section) => section.id === id)) fail(line, `section ${id} twice`);
  const section = { id, title: title.trim(), rules: [] };
  return { ...state, sections: [...state.sections, section], open: true };
}

/** The state with one rule added to the open section, which must be the rule's own. */
function addRule(state, match, line) {
  const id = `${match[1]}.${match[2]}`;
  const current = state.sections.at(-1);
  if (!state.open || current === undefined) fail(line, `rule ${id} is outside a numbered section`);
  if (current.id !== match[1]) fail(line, `rule ${id} is under section ${current.id}`);
  if (state.sections.some((section) => section.rules.includes(id))) fail(line, `rule ${id} twice`);
  const section = { ...current, rules: [...current.rules, id] };
  return { ...state, sections: [...state.sections.slice(0, -1), section] };
}

/** One line of the page read into the state. */
function readLine(state, text, index) {
  const line = index + 1;
  if (FENCE.test(text)) return { ...state, fenced: !state.fenced };
  if (state.fenced) return state;
  const section = SECTION.exec(text);
  if (section) return openSection(state, section, line);
  if (ANY_SECTION.test(text)) return { ...state, open: false };
  const rule = RULE.exec(text);
  return rule ? addRule(state, rule, line) : state;
}

/** The standard's numbered sections, each with its title and its rules' ids, in the page's order. */
export function standardRules(markdown) {
  const start = { sections: [], open: false, fenced: false };
  const { sections } = markdown.split('\n').reduce(readLine, start);
  return { note: GENERATED_NOTE, sections };
}

/** The file's bytes: two-space JSON and a final newline. */
export function serialise(data) {
  return `${JSON.stringify(data, null, 2)}\n`;
}

/** Writes the list and says what it holds. Exit 0 when written, 1 when it could not be. */
export function run(root = ROOT, out = (line) => process.stdout.write(`${line}\n`)) {
  try {
    const source = path.join(root, SOURCE_PATH);
    if (!existsSync(source)) {
      throw new StandardError(`${SOURCE_PATH} is not here: only the template carries the standard`);
    }
    const data = standardRules(readFileSync(source, 'utf8'));
    writeFileSync(path.join(root, OUTPUT_PATH), serialise(data));
    const rules = data.sections.reduce((sum, section) => sum + section.rules.length, 0);
    out(`Wrote ${OUTPUT_PATH}: ${data.sections.length} sections, ${rules} rules.`);
    return 0;
  } catch (error) {
    process.stderr.write(`error: ${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

// Node runs the main module from its real path, so compare real paths (a linked checkout).
function invokedDirectly() {
  const entry = process.argv[1];
  return (
    entry !== undefined &&
    existsSync(entry) &&
    pathToFileURL(realpathSync(entry)).href === import.meta.url
  );
}

if (invokedDirectly()) process.exitCode = run();
