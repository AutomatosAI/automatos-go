// The licence list Settings → Licences shows (docs/app-standard.md rule 8.3): every package the app
// is built from, read from package-lock.json and node_modules, written to src/about/licences.json.
//
//   node scripts/generate-licences.mjs
//
// Run it after any change to the dependencies (npm install, npm update, a new package), then commit
// the JSON with the lockfile. scripts/__tests__/release-licences.test.ts runs the same function in
// CI and fails while the committed file differs from what this script would write.
//
// What is listed: every package the lockfile installs that is not marked dev, the app itself left
// out. An optional package that names an `os` or a `cpu` is left out too: it is a native binary for
// the computer that builds the app (another platform's twin is never installed there), so it never
// reaches a phone, and the package that pulls it in is listed with the same licence. A package
// installed at two places at one version is listed once.
//
// What each entry holds: the name and version from the installed package.json (the version must be
// the lockfile's, or node_modules is not this lockfile's install), the licence it declares, and the
// text of its licence files (LICENSE, LICENCE, COPYING, UNLICENSE and their variants in any case,
// then a NOTICE file, which Apache-2.0 asks to be passed on). A package with none has no text. Each
// distinct text is stored once, under the first 12 hex digits of its SHA-256. The file holds no
// path, no date and nothing from the machine that ran it, in a fixed order, so two runs over the
// same install write the same bytes. Node's built-ins only; nothing is fetched.

import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Where the list is written, from the repository root. */
export const OUTPUT_PATH = 'src/about/licences.json';
/** The one line at the top of the file, for a person who opens it. */
export const GENERATED_NOTE =
  'Generated by scripts/generate-licences.mjs from package-lock.json and node_modules. Do not edit by hand: run node scripts/generate-licences.mjs.';
/** Hex digits of a text's SHA-256 that name it. */
export const TEXT_KEY_LENGTH = 12;

const NODE_MODULES = 'node_modules/';
const LICENCE_FILE = /^(?:un)?(?:licen[cs]e|copying)(?:[.\-_][\w.-]*)?$/i;
const NOTICE_FILE = /^notice(?:\.(?:md|txt))?$/i;
const NOT_A_TEXT = /\.(?:[cm]?[jt]s|json|map)$/i;
const BYTE_ORDER_MARK = /^\uFEFF/;
const TEXT_SEPARATOR = '\n\n';
const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** The install does not match the lockfile, or a package cannot be read. */
export class LicenceError extends Error {}

/** Code-unit order, the same on every machine and in every locale. */
export function byCodeUnit(a, b) {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}

/** A native binary for one platform: optional, with an `os` or `cpu` the lockfile names. */
export function isPlatformBinary(entry) {
  return entry.optional === true && (entry.os !== undefined || entry.cpu !== undefined);
}

/**
 * The lockfile keys of every package that ships, in order: under node_modules/, not dev, not a
 * platform binary. The app itself is the key '' and is never one of them.
 * @returns {string[]}
 */
export function shippedKeys(lock) {
  return Object.keys(lock.packages ?? {})
    .filter((key) => key.startsWith(NODE_MODULES))
    .filter((key) => lock.packages[key].dev !== true && !isPlatformBinary(lock.packages[key]))
    .sort(byCodeUnit);
}

/** A trimmed string, or null for anything blank or not a string. */
function nonBlank(value) {
  return typeof value === 'string' && value.trim() !== '' ? value.trim() : null;
}

/** The older `licenses` field: one id, or several read as a choice between them. */
function olderLicences(licenses) {
  if (!Array.isArray(licenses)) return nonBlank(licenses);
  const types = licenses
    .map((each) => nonBlank(typeof each === 'string' ? each : each?.type))
    .filter((type) => type !== null);
  if (types.length === 0) return null;
  return types.length === 1 ? types[0] : `(${types.join(' OR ')})`;
}

/** The licence a package.json declares, as written; null when it declares none. */
export function declaredLicence(manifest) {
  return (
    nonBlank(manifest.license) ??
    nonBlank(manifest.license?.type) ??
    olderLicences(manifest.licenses)
  );
}

/** One text as it is stored: no byte-order mark, LF line ends, no trailing spaces or blank ends. */
export function normaliseText(raw) {
  return raw
    .replace(BYTE_ORDER_MARK, '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .replace(/^\n+|\n+$/g, '');
}

/** 0 for a licence file, 1 for a notice (joined after the licences), null for anything else. */
export function licenceFileRank(name) {
  if (NOT_A_TEXT.test(name)) return null;
  if (LICENCE_FILE.test(name)) return 0;
  return NOTICE_FILE.test(name) ? 1 : null;
}

/**
 * A package's licence files in the order they are joined: licences, then a notice, each by name.
 * @param {readonly string[]} names
 */
export function licenceFiles(names) {
  return names
    .map((name) => ({ name, rank: licenceFileRank(name) }))
    .filter((file) => file.rank !== null)
    .sort((a, b) => a.rank - b.rank || byCodeUnit(a.name, b.name))
    .map((file) => file.name);
}

/** The texts joined into one, or null when the package has none (or only empty ones). */
export function joinTexts(texts) {
  const kept = texts.map(normaliseText).filter((text) => text !== '');
  return kept.length === 0 ? null : kept.join(TEXT_SEPARATOR);
}

/** A text's key: the first TEXT_KEY_LENGTH hex digits of its SHA-256. */
export function textKey(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex').slice(0, TEXT_KEY_LENGTH);
}

function checkedPackage(key, entry, read) {
  const { manifest, text } = read(key);
  if (typeof manifest.name !== 'string' || manifest.name === '') {
    throw new LicenceError(`${key}: its package.json has no name`);
  }
  if (manifest.version !== entry.version) {
    throw new LicenceError(
      `${key}: node_modules has ${manifest.version}, package-lock.json ${entry.version}. Run npm ci --ignore-scripts, then this script again.`,
    );
  }
  return {
    name: manifest.name,
    version: manifest.version,
    licence: declaredLicence(manifest),
    text,
  };
}

function storeText(texts, text) {
  if (text === null) return null;
  const key = textKey(text);
  const held = texts.get(key);
  if (held !== undefined && held !== text) {
    throw new LicenceError(`two licence texts share the key ${key}: lengthen TEXT_KEY_LENGTH`);
  }
  texts.set(key, text);
  return key;
}

function byNameThenVersion(a, b) {
  return byCodeUnit(a.name, b.name) || byCodeUnit(a.version, b.version);
}

/**
 * The list from a lockfile and a reader of installed packages. Pure but for `read`, which takes a
 * lockfile key and gives that package's package.json and its joined licence text (or null).
 * @param {{ packages?: Record<string, Record<string, unknown>> }} lock
 * @param {(key: string) => { manifest: Record<string, unknown>, text: string | null }} read
 * @returns {{ note: string, packages: { name: string, version: string, licence: string | null, text: string | null }[], texts: Record<string, string> }}
 */
export function buildLicenceData(lock, read) {
  const seen = new Set();
  const texts = new Map();
  const packages = [];
  for (const key of shippedKeys(lock)) {
    const found = checkedPackage(key, lock.packages[key], read);
    const id = `${found.name}@${found.version}`;
    if (seen.has(id)) continue;
    seen.add(id);
    packages.push({ ...found, text: storeText(texts, found.text) });
  }
  const keys = [...texts.keys()].sort(byCodeUnit);
  return {
    note: GENERATED_NOTE,
    packages: packages.sort(byNameThenVersion),
    texts: Object.fromEntries(keys.map((key) => [key, texts.get(key)])),
  };
}

/** The file's bytes: two-space JSON and a final newline. */
export function serialise(data) {
  return `${JSON.stringify(data, null, 2)}\n`;
}

/**
 * A reader over one node_modules folder. The folder is resolved to its real path first, so a
 * checkout whose node_modules is a link to another checkout's reads the same files.
 */
export function installReader(nodeModulesDir) {
  const real = realpathSync(nodeModulesDir);
  return (key) => {
    const dir = path.join(real, ...key.slice(NODE_MODULES.length).split('/'));
    const manifestFile = path.join(dir, 'package.json');
    if (!existsSync(manifestFile)) {
      throw new LicenceError(`${key} is not installed. Run npm ci --ignore-scripts first.`);
    }
    const names = readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => entry.name);
    const text = joinTexts(
      licenceFiles(names).map((name) => readFileSync(path.join(dir, name), 'utf8')),
    );
    return { manifest: JSON.parse(readFileSync(manifestFile, 'utf8')), text };
  };
}

/** The list for a repository: its package-lock.json over its node_modules. */
export function licenceData(root = ROOT) {
  const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
  return buildLicenceData(lock, installReader(path.join(root, 'node_modules')));
}

/** Writes the list and says what it holds. Exit 0 when written, 1 when it could not be. */
export function run(root = ROOT, out = (line) => process.stdout.write(`${line}\n`)) {
  try {
    const data = licenceData(root);
    const bytes = serialise(data);
    const file = path.join(root, OUTPUT_PATH);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, bytes);
    const size = Buffer.byteLength(bytes, 'utf8');
    const withText = data.packages.filter((each) => each.text !== null).length;
    out(
      `Wrote ${OUTPUT_PATH}: ${data.packages.length} packages (${withText} with a licence file), ` +
        `${Object.keys(data.texts).length} distinct texts, ${size} bytes.`,
    );
    return 0;
  } catch (error) {
    process.stderr.write(`error: ${error instanceof Error ? error.message : String(error)}\n`);
    return 1;
  }
}

// Node runs the main module from its real path, so compare real paths (a linked checkout).
function invokedDirectly() {
  const entry = process.argv[1];
  return (
    entry !== undefined &&
    existsSync(entry) &&
    pathToFileURL(realpathSync(entry)).href === import.meta.url
  );
}

if (invokedDirectly()) process.exitCode = run();
